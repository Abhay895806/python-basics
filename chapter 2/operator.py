# Arithmetic Operators
a = 10
b = 5
c = a + b  # Addition
d = a - b  # Subtraction
e = a * b  # Multiplication
f = a / b  # Division
print(c)  # Output: 15
print(d)  # Output: 5   
print(e)  # Output: 50
print(f)  # Output: 2.0



#Assignment Operators
x = 5
x += 2  # Equivalent to x = x + 2
x -= 2  # Equivalent to x = x - 2
x *= 2  # Equivalent to x = x * 2
x /= 2  # Equivalent to x = x / 2
print(x)  # Output: 2.5

#Comparison Operators
    
print(a == b)  # Output: False
print(a != b)  # Output: True
print(a > b)   # Output: True
print(a < b)   # Output: False
print(a >= b)  # Output: True
print(a <= b)  # Output: False

#Logical Operators
x = True   or False
#Truth table for logical operators
print(x and True)  # Output: True
print(x or False)  # Output: True

print(x)  # Output: True
